"""Builds the launcher icon set: a gold compass medallion (the game's emblem) over the
steppe heart of the board map.

Usage: python -I tools/icon/make_icon.py app/src/main/res/drawable-nodpi/board_map.jpg build/icon --render
Writes an Android res/ tree (vector foreground and monochrome layers, adaptive icon
XML) plus SVG/HTML sources; with --render, headless Chrome turns them into the map
background layer, the legacy PNG icons (Android 7) and the 512 px Play Store icon.
Copy build/icon/res into app/src/main/res and build/icon/store/icon-512.png into store/.
"""
import math
import subprocess
import sys
from pathlib import Path

MAP, OUT = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
RENDER = "--render" in sys.argv
CHROME = r"C:\Program Files\Google\Chrome\Application\chrome.exe"

C = 54.0  # centre of the 108 x 108 adaptive icon canvas
LIGHT, DARK = "#F2C46B", "#A8772A"        # cardinal points, lit and shaded halves
DIAG_LIGHT, DIAG_DARK = "#C99A45", "#8A6122"
RING, RING_INNER, INK = "#E0A944", "#A8772A", "#140F0A"

# Map crop (pixels of board_map.jpg) shown behind the medallion: yurts, the sacred mountain, camels.
CROP_X, CROP_Y, CROP = 600, 170, 780
MAP_W, MAP_H = 1953, 1360


def pt(r: float, deg: float) -> tuple:
    """Point at radius r and compass bearing deg (0 = up)."""
    a = math.radians(deg)
    return C + r * math.sin(a), C - r * math.cos(a)


def poly(*points) -> str:
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in points) + " Z"


def circle(r: float) -> str:
    return f"M{C - r:.2f},{C:.2f} a{r},{r} 0 1,1 {2 * r:.2f},0 a{r},{r} 0 1,1 {-2 * r:.2f},0 Z"


def points() -> list:
    """(pathData, colour) for the eight compass points, bevelled like emblem_compass.xml."""
    out = []
    for bearing in (0, 90, 180, 270):
        tip, left, right = pt(26.5, bearing), pt(6.2, bearing - 45), pt(6.2, bearing + 45)
        out += [(poly(tip, left, (C, C)), LIGHT), (poly(tip, right, (C, C)), DARK)]
    for bearing in (45, 135, 225, 315):
        tip, a, b = pt(17.5, bearing), pt(4.4, bearing - 45), pt(4.4, bearing + 45)
        out += [(poly(tip, a, (C, C)), DIAG_LIGHT), (poly(tip, b, (C, C)), DIAG_DARK)]
    return out


# ---------- vector layers (also reused, as SVG, for the PNG renders) ----------

FILLS = [(circle(32.6), "#000000", 0.35), (circle(31), INK, 0.92)] + [(d, c, 1.0) for d, c in points()] + [
    (circle(2.6), INK, 1.0)]
STROKES = [(circle(31), RING, 2.6), (circle(28.2), RING_INNER, 0.9), (circle(20.5), DIAG_DARK, 0.7)]


def vector(paths_xml: str, comment: str) -> str:
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{paths_xml}</vector>
'''


def foreground_xml() -> str:
    xml = ""
    for d, color, alpha in FILLS[:2]:
        xml += f'    <path android:fillColor="{color}" android:fillAlpha="{alpha}" android:pathData="{d}" />\n'
    for d, color, width in STROKES:
        xml += f'    <path android:strokeColor="{color}" android:strokeWidth="{width}" android:pathData="{d}" />\n'
    for d, color, _ in FILLS[2:]:
        xml += f'    <path android:fillColor="{color}" android:pathData="{d}" />\n'
    return vector(xml, "Launcher icon foreground: the gold compass medallion (the game's emblem, as on the splash\n"
                       "     screen). Generated by tools/icon/make_icon.py; it stays inside the 66 dp safe circle.")


def monochrome_xml() -> str:
    """Single-colour silhouette for Android 13+ themed icons (the system tints it)."""
    xml = f'    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="2.6" android:pathData="{circle(31)}" />\n'
    for d, _ in points():
        xml += f'    <path android:fillColor="#FFFFFFFF" android:pathData="{d}" />\n'
    return vector(xml, "Themed-icon layer (Android 13+): the compass alone, tinted by the system.\n"
                       "     Generated by tools/icon/make_icon.py.")


def adaptive_xml() -> str:
    return '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''


# ---------- SVG compositions for the bitmaps ----------

def svg(view: str, size: int, clip: str, layers: str) -> str:
    k = 108 / CROP
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="{view}">
  <defs>
    <radialGradient id="vignette" cx="54" cy="54" r="76" gradientUnits="userSpaceOnUse">
      <stop offset="0.30" stop-color="{INK}" stop-opacity="0"/>
      <stop offset="1" stop-color="{INK}" stop-opacity="0.70"/>
    </radialGradient>
    <clipPath id="shape">{clip}</clipPath>
  </defs>
  <g clip-path="url(#shape)">
    <image href="{MAP.as_uri()}" x="{-CROP_X * k:.3f}" y="{-CROP_Y * k:.3f}" width="{MAP_W * k:.3f}" height="{MAP_H * k:.3f}"/>
    <rect width="108" height="108" fill="#3A2A12" fill-opacity="0.18"/>
    <rect width="108" height="108" fill="url(#vignette)"/>
    {layers}
  </g>
</svg>'''


def medallion_svg() -> str:
    out = ""
    for d, color, alpha in FILLS[:2]:
        out += f'<path d="{d}" fill="{color}" fill-opacity="{alpha}"/>'
    for d, color, width in STROKES:
        out += f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{width}"/>'
    for d, color, _ in FILLS[2:]:
        out += f'<path d="{d}" fill="{color}"/>'
    return out


FULL = '<rect width="108" height="108"/>'
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}

renders = []  # (svg text, size, output png)
for name, scale in DENSITIES.items():
    # Adaptive background layer: the whole 108 dp canvas, map and vignette only.
    renders.append((svg("0 0 108 108", round(108 * scale), FULL, ""), round(108 * scale),
                    OUT / "res" / f"mipmap-{name}" / "ic_launcher_background.png"))
    # Android 7 has no adaptive icons: the visible 72 dp middle, with a shape of its own.
    size = round(48 * scale)
    renders.append((svg("18 18 72 72", size, '<rect x="20" y="20" width="68" height="68" rx="13"/>', medallion_svg()), size,
                    OUT / "res" / f"mipmap-{name}" / "ic_launcher.png"))
    renders.append((svg("18 18 72 72", size, '<circle cx="54" cy="54" r="34"/>', medallion_svg()), size,
                    OUT / "res" / f"mipmap-{name}" / "ic_launcher_round.png"))
# Play Store listing icon: full square (Play rounds the corners), a little more map around the medallion.
renders.append((svg("13 13 82 82", 512, FULL, medallion_svg()), 512, OUT / "store" / "icon-512.png"))

(OUT / "res" / "drawable").mkdir(parents=True, exist_ok=True)
(OUT / "res" / "mipmap-anydpi-v26").mkdir(parents=True, exist_ok=True)
(OUT / "res" / "drawable" / "ic_launcher_foreground.xml").write_text(foreground_xml(), encoding="utf-8")
(OUT / "res" / "drawable" / "ic_launcher_monochrome.xml").write_text(monochrome_xml(), encoding="utf-8")
for icon in ("ic_launcher.xml", "ic_launcher_round.xml"):
    (OUT / "res" / "mipmap-anydpi-v26" / icon).write_text(adaptive_xml(), encoding="utf-8")

work = OUT / "work"
work.mkdir(parents=True, exist_ok=True)
for i, (text, size, png) in enumerate(renders):
    png.parent.mkdir(parents=True, exist_ok=True)
    page = work / f"r{i}.html"
    page.write_text(f'<!doctype html><html><body style="margin:0;background:transparent">{text}</body></html>', encoding="utf-8")
    if RENDER:
        subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--allow-file-access-from-files",
                        "--force-device-scale-factor=1", "--default-background-color=00000000",
                        f"--user-data-dir={work / 'chrome-profile'}", f"--window-size={size},{size}",
                        f"--screenshot={png}", page.as_uri()], check=True, capture_output=True, timeout=60)
        print(f"{png.relative_to(OUT)}: {size} px")
print(f"{len(renders)} renders {'done' if RENDER else 'prepared'}")
